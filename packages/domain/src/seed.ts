function room(
  number: string,
  type: HotelState["rooms"][number]["type"],
  status: HotelState["rooms"][number]["status"],
  features: string[],
): HotelState["rooms"][number] {
  return {
    id: `room-${number}`,
    number,
    floor: Number(number[0]),
    type,
    status,
    features,
  };
}

function guest(
  id: string,
  name: string,
  loyaltyTier: HotelState["guests"][number]["loyaltyTier"],
  notes: string,
): HotelState["guests"][number] {
  const handle = name.toLowerCase().replace(/[^a-z]+/g, ".");
  return {
    id,
    name,
    email: `${handle}@guests.lumen-harbor.example`,
    phone: "555-0148",
    loyaltyTier,
    notes,
  };
}
